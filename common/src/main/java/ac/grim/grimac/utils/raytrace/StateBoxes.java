    public static Box getBox(StateType state) {
        Box box = BOXES.get(state);
        if (box == null) {
            if (WARNED.add(state)) {
                LOG.warning("StateBoxes: нет хитбокса для " + state.getName() + ", используется FULL");
            }
            return FULL;
        }
        return box;
    }

    public static boolean isKnown(StateType state) {
        return BOXES.containsKey(state);
    }

    public static boolean isStateDependent(StateType state) {
        return STATE_DEPENDENT.contains(state);
    }

    public static boolean requiresHeldItem(StateType state) {
        return NEEDS_HELD_ITEM.contains(state);
    }

    public static boolean hasOffset(StateType state) {
        return OFFSET_XZ.contains(state);
    }

    public static double[] getOffset(StateType state, int x, int z) {
        if (!OFFSET_XZ.contains(state)) return new double[]{0.0, 0.0};
        long seed = (long) (x * 3129871) ^ (long) z * 116129781L;
        seed = seed * seed * 42317861L + seed * 11L;
        seed >>= 16;
        double dx = clamp(((double) ((float) (seed & 15L) / 15.0F) - 0.5D) * 0.5D, -0.25D, 0.25D);
        double dz = clamp(((double) ((float) (seed >> 8 & 15L) / 15.0F) - 0.5D) * 0.5D, -0.25D, 0.25D);
        return new double[]{dx, dz};
    }

    private static double clamp(double v, double min, double max) {
        return v < min ? min : Math.min(v, max);
    }

    public static Box getBox(StateType state, int x, int z) {
        Box box = getBox(state);
        if (!OFFSET_XZ.contains(state)) return box;
        double[] o = getOffset(state, x, z);
        return box.offset(o[0], 0, o[1]);
    }

    public static Box getBoxWithOffset(StateType state, int x, int z) {
        return getBox(state, x, z);
    }

    public static boolean isFullCube(StateType state) {
        Box box = getBox(state);
        return box.minX == 0 && box.minY == 0 && box.minZ == 0 &&
                box.maxX == 1 && box.maxY == 1 && box.maxZ == 1;
    }

    public static boolean isFullCube(Box box) {
        return box.minX == 0 && box.minY == 0 && box.minZ == 0 &&
                box.maxX == 1 && box.maxY == 1 && box.maxZ == 1;
    }

    public static boolean isNonFull(StateType state) {
        return !isFullCube(getBox(state));
    }

    public static boolean isEmpty(StateType state) {
        Box box = getBox(state);
        return box.minX == box.maxX || box.minY == box.maxY || box.minZ == box.maxZ;
    }

    public static class Box {
        public final double minX, minY, minZ;
        public final double maxX, maxY, maxZ;

        public Box(double minX, double minY, double minZ, double maxX, double maxY, double maxZ) {
            this.minX = minX;
            this.minY = minY;
            this.minZ = minZ;
            this.maxX = maxX;
            this.maxY = maxY;
            this.maxZ = maxZ;
        }

        public Box offset(double x, double y, double z) {
            return new Box(minX + x, minY + y, minZ + z, maxX + x, maxY + y, maxZ + z);
        }

        public boolean intersects(Box other) {
            return this.minX < other.maxX && this.maxX > other.minX &&
                    this.minY < other.maxY && this.maxY > other.minY &&
                    this.minZ < other.maxZ && this.maxZ > other.minZ;
        }

        public boolean contains(double x, double y, double z) {
            return x >= minX && x <= maxX &&
                    y >= minY && y <= maxY &&
                    z >= minZ && z <= maxZ;
        }

        @Override
        public String toString() {
            return String.format("Box[%.2f,%.2f,%.2f -> %.2f,%.2f,%.2f]",
                    minX, minY, minZ, maxX, maxY, maxZ);
        }
    }
